#[cfg(test)]
mod rendered_spans {
    use super::*;
    #[test]
    fn spans_follow_the_authoritative_cursor_across_empty_partial_and_silent_tails() {
        let session = crate::Stimulus {
            duration_seconds: 17.0 / 8000.0,
            fade_seconds: 0.0,
            components: alloc::vec![],
        }
        .session(SampleRate::new(8000).unwrap())
        .unwrap();
        let mut renderer = session.into_renderer();
        let mut cursor = 0;
        for size in [0, 1, 3, 0, 5, 2, 19, 0, 3] {
            let mut buffer = alloc::vec![[1.0; 2]; size];
            let span = renderer.render(&mut buffer);
            let active = size.min(usize::try_from(17 - cursor).unwrap());
            assert_eq!(span.start(), cursor);
            assert_eq!(span.frames(), active);
            assert_eq!(span.end(), cursor + active as u64);
            assert!(buffer[active..].iter().all(|frame| *frame == [0.0; 2]));
            cursor = span.end();
        }
        assert_eq!(cursor, 17);
    }
}
