    #[test]
    fn generated_compositions_respect_stored_linear_bounds_counts_routes_and_partitions() {
        let strategy = (
            prop::sample::select(vec![1_u32, 8_000, 44_100, 48_000, 96_000, 768_000]),
            1_u32..=513,
            any::<u16>(),
            prop::collection::vec(
                (
                    0_u8..3,
                    any::<bool>(),
                    0_u8..3,
                    1_u32..=63,
                    0_u32..=100,
                    prop::sample::select(vec![-30.0, -60.0, -180.0, -6_400.0]),
                ),
                0..=16,
            ),
            prop::collection::vec(0_usize..=97, 0..=12),
        );
        let config = Config {
            cases: 128,
            failure_persistence: None,
            max_shrink_iters: 256,
            ..Config::default()
        };
        let cases = core::cell::Cell::new(0);
        TestRunner::new(config)
            .run(&strategy, |(hz, frames, fade, parts, blocks)| {
                let rate = SampleRate::new(hz).unwrap();
                let fade = u32::from(fade) % ((frames - 1) / 2 + 1);
                let components = parts
                    .into_iter()
                    .map(|(ear, click, kind, numerator, depth, peak_dbfs)| {
                        let ears = match ear {
                            0 => Ears::Both,
                            1 => Ears::Left,
                            _ => Ears::Right,
                        };
                        let modulation = match kind {
                            0 => None,
                            1 => Some(Modulation::Sinusoidal {
                                rate_hz: f64::from(hz) / 128.0,
                                depth: f64::from(depth) / 100.0,
                            }),
                            _ => Some(Modulation::Rectangular {
                                rate_hz: f64::from(hz) / 128.0,
                                width_seconds: 2.0 / f64::from(hz),
                            }),
                        };
                        if click {
                            Component::Click {
                                ears,
                                rate_hz: f64::from(hz) * f64::from(numerator) / 1_024.0,
                                width_seconds: 2.0 / f64::from(hz),
                                peak_dbfs,
                                modulation,
                            }
                        } else {
                            Component::Tone {
                                ears,
                                frequency_hz: f64::from(hz) * f64::from(numerator) / 1_024.0,
                                peak_dbfs,
                                modulation,
                            }
                        }
                    })
                    .collect();
                let stimulus = Stimulus {
                    duration_seconds: f64::from(frames) / f64::from(hz),
                    fade_seconds: f64::from(fade) / f64::from(hz),
                    components,
                };
                let session = stimulus.session(rate).unwrap();
                prop_assert_eq!(session.frames(), u64::from(frames));
                prop_assert_eq!(session.fade_frames(), u64::from(fade));
                // This reads the actual private linear bound, without log10/pow round trips.
                let bound = session.peak;
                let mut whole = vec![[9.0; 2]; usize::try_from(frames).unwrap() + 3];
                let mut renderer = session.clone().into_renderer();
                prop_assert_eq!(
                    renderer.render(&mut whole).frames(),
                    usize::try_from(frames).unwrap()
                );
                for frame in &whole {
                    for ear in 0..2 {
                        prop_assert!(frame[ear].is_finite());
                        prop_assert!(frame[ear].abs() <= bound[ear]);
                        prop_assert!(frame[ear].abs() <= 1.0);
                    }
                }
                prop_assert!(
                    whole[usize::try_from(frames).unwrap()..]
                        .iter()
                        .flatten()
                        .all(|sample| sample.to_bits() == 0)
                );
                let mut renderer = session.into_renderer();
                let mut actual = Vec::new();
                for count in blocks
                    .into_iter()
                    .chain([usize::try_from(frames).unwrap() + 3])
                {
                    let mut block = vec![[9.0; 2]; count];
                    let produced = renderer.render(&mut block).frames();
                    prop_assert!(
                        block[produced..]
                            .iter()
                            .flatten()
                            .all(|sample| sample.to_bits() == 0)
                    );
                    actual.extend_from_slice(&block[..produced]);
                }
                prop_assert!(renderer.is_complete());
                prop_assert_eq!(actual.len(), usize::try_from(frames).unwrap());
                for (actual, expected) in actual.iter().zip(&whole) {
                    prop_assert_eq!(actual.map(f64::to_bits), expected.map(f64::to_bits));
                }
                let mut invalid = stimulus.clone();
                invalid.fade_seconds = f64::from(frames.div_ceil(2)) / f64::from(hz);
                prop_assert!(invalid.session(rate).is_err());
                let mut boundary = Stimulus {
                    duration_seconds: 16.0 / f64::from(hz),
                    fade_seconds: 0.0,
                    components: vec![Component::Tone {
                        ears: Ears::Both,
                        frequency_hz: f64::from(hz) / 2.0,
                        peak_dbfs: -30.0,
                        modulation: None,
                    }],
                };
                prop_assert!(boundary.session(rate).is_err());
                if let Component::Tone { frequency_hz, .. } = &mut boundary.components[0] {
                    *frequency_hz = frequency_hz.next_down();
                }
                prop_assert!(boundary.session(rate).is_ok());
                cases.set(cases.get() + 1);
                Ok(())
            })
            .unwrap();
        assert_eq!(cases.get(), 128);
    }
