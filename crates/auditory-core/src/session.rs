    #[test]
    fn late_fades_use_symmetric_quantized_edges_with_an_independent_sine_squared_oracle() {
        for frames in [1, 11, 158_760_000, 345_600_000, Session::MAX_FRAMES] {
            for fade in [0, 1, 4_410, (frames - 1) / 2] {
                if 2 * fade >= frames {
                    continue;
                }
                let envelope = Envelope::new(frames, fade);
                for depth in [0, 1, fade.saturating_sub(1), fade, fade + 1] {
                    if depth >= frames {
                        continue;
                    }
                    let actual = envelope.gain_at(depth);
                    let distance = depth.min(frames - 1 - depth);
                    let expected = if fade == 0 || distance >= fade {
                        1.0
                    } else {
                        (core::f64::consts::FRAC_PI_2 * numeric::frames_to_f64(distance)
                            / numeric::frames_to_f64(fade))
                        .sin()
                        .powi(2)
                    };
                    // Division/argument rounding plus bounded sin/cos evaluation;
                    // use absolute error where cosine subtraction loses relative precision.
                    assert!((actual - expected).abs() <= 8.0 * f64::EPSILON);
                    assert_eq!(
                        actual.to_bits(),
                        envelope.gain_at(frames - 1 - depth).to_bits()
                    );
                }
                assert_eq!(envelope.gain_at(frames), 0.0);
                if fade > 0 {
                    assert_eq!(envelope.gain_at(0), 0.0);
                    assert_eq!(envelope.gain_at(frames - 1), 0.0);
                }
            }
        }
        // Moving an edge by one frame must be visible to the independent oracle.
        assert!(
            (Envelope::new(11, 4).gain_at(1)
                - (core::f64::consts::FRAC_PI_2 * 2.0 / 4.0).sin().powi(2))
            .abs()
                > 0.1
        );
    }
    fn stream_catalog(seconds: u32, hz: u32) {
        let mut stimulus = crate::Preset::parse(
            crate::catalog::find("martorell-2019-tone-pips-40-hz")
                .unwrap()
                .text,
        )
        .unwrap()
        .stimulus;
        stimulus.duration_seconds = f64::from(seconds);
        let session = stimulus.session(SampleRate::new(hz).unwrap()).unwrap();
        let count = session.frames();
        let fade = session.fade_frames();
        let bound = session.peak;
        let mut renderer = session.into_renderer();
        let mut buffer = [[0.0; 2]; 4_096];
        let mut offset = 0;
        while !renderer.is_complete() {
            let active = renderer.render(&mut buffer).frames();
            assert!(active > 0);
            for (index, frame) in buffer[..active].iter().enumerate() {
                let n = offset + u64::try_from(index).unwrap();
                assert!(frame[0].abs() <= bound[0] && frame[1].abs() <= bound[1]);
                assert_eq!(frame[0].to_bits(), frame[1].to_bits());
                if n < 32 || n + 32 >= count || n % 8_191 == 0 {
                    // Integer-reduced declared 10 kHz carrier and 40 Hz / 1 ms
                    // gate, rather than the production-rounded oscillator step.
                    let remainder = (u128::from(n) * 10_000) % u128::from(hz);
                    let cycles = f64::from(u32::try_from(remainder).unwrap()) / f64::from(hz);
                    let gate_remainder = (u128::from(n) * 40) % u128::from(hz);
                    // Exclude only the explicitly bounded adjacent edge frame.
                    let edge_units = gate_remainder
                        .min(u128::from(hz) - gate_remainder)
                        .min(gate_remainder.abs_diff(u128::from(hz) * 40 / 1_000));
                    if edge_units > 40 {
                        let open = gate_remainder * 1_000 < u128::from(hz) * 40;
                        let depth = n.min(count - 1 - n);
                        let gain = if depth >= fade {
                            1.0
                        } else {
                            (core::f64::consts::FRAC_PI_2 * numeric::frames_to_f64(depth)
                                / numeric::frames_to_f64(fade))
                            .sin()
                            .powi(2)
                        };
                        let expected = if open {
                            0.1 * (core::f64::consts::TAU * cycles).sin() * gain
                        } else {
                            0.0
                        };
                        let u = f64::EPSILON / 2.0;
                        let phase_error =
                            numeric::frames_to_f64(n) * u * (1.0 + 10_000.0 / f64::from(hz)) + u;
                        let allowance = 0.1 * (core::f64::consts::TAU * phase_error + 48.0 * u);
                        assert!(
                            (frame[0] - expected).abs() <= allowance,
                            "{hz}, frame {n}: {} vs {expected}, limit {allowance}",
                            frame[0]
                        );
                    }
                }
            }
            assert!(
                buffer[active..]
                    .iter()
                    .flatten()
                    .all(|sample| sample.to_bits() == 0)
            );
            offset += u64::try_from(active).unwrap();
        }
        assert_eq!(offset, count);
        assert_eq!(renderer.render(&mut buffer).frames(), 0);
        assert!(buffer.iter().flatten().all(|sample| sample.to_bits() == 0));
    }
